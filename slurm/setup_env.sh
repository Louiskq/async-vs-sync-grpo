#!/bin/bash
#SBATCH --job-name=agrpo-setup
#SBATCH --gres=gpu:1
#SBATCH --time=01:00:00
#SBATCH --output=logs/%x-%j.out
# Build the venv (M0). Run on a COMPUTE node: login nodes have a 4 GiB memory cap that pip/torch installs can hit.
#   sbatch slurm/setup_env.sh        (needs slurm/env.sh; PYTHON defaults to python3.11)
# Writes requirements.lock and environment.md (pip freeze + driver/CUDA info) at the repo root.
set -euo pipefail
cd "${SLURM_SUBMIT_DIR:-$(pwd)}"
source slurm/env.sh
PYTHON=${PYTHON:-python3.11}
VLLM_VERSION=${VLLM_VERSION:-0.26.0}   # last version verified on Isambard-AI GH200; TRL 1.18.2 allows >=0.23,<0.34
TRL_VERSION=${TRL_VERSION:-1.18.2}

# 1. CUDA forward-compat libs (Isambard-AI: driver 565 = CUDA 12.7; vLLM wheels need the CUDA 13 runtime).
if [[ -n "${CUDA_COMPAT_DIR:-}" && ! -e $CUDA_COMPAT_DIR/libcuda.so ]]; then
    ROOT=${CUDA_COMPAT_DIR%/usr/local/cuda-13.0/compat}
    mkdir -p "$ROOT" && pushd "$ROOT" >/dev/null
    curl -sLO https://developer.download.nvidia.com/compute/cuda/repos/sles15/sbsa/cuda-compat-13-0-580.95.05-1.aarch64.rpm
    rpm2cpio cuda-compat-13-0-580.95.05-1.aarch64.rpm | cpio -idm
    popd >/dev/null
fi
[[ -n "${CUDA_COMPAT_DIR:-}" ]] && export LD_LIBRARY_PATH=$CUDA_COMPAT_DIR:${LD_LIBRARY_PATH:-}

# 2. venv + packages. vLLM first (it pins torch), then TRL, then project deps.
"$PYTHON" -m venv "$VENV"
"$VENV/bin/pip" install -q -U pip
"$VENV/bin/pip" install -q "vllm==$VLLM_VERSION"
"$VENV/bin/pip" install -q "trl==$TRL_VERSION"
"$VENV/bin/pip" install -q nvidia-ml-py pyyaml matplotlib pytest ruff ninja

# 3. A consistent CUDA 13.0 toolchain for anything vLLM/flashinfer JIT-compiles (nvcc, crt and nvvm must match).
"$VENV/bin/pip" install -q "nvidia-cuda-nvcc==13.0.88" "nvidia-cuda-crt==13.0.88" "nvidia-nvvm==13.0.88"

# 4. Symlinks the pip CUDA wheels don't ship (flashinfer links -L<cuda>/lib64 -L<cuda>/lib64/stubs -lcudart -lcuda).
PYVER=$("$VENV/bin/python" -c 'import sys; print(f"python{sys.version_info.major}.{sys.version_info.minor}")')
CU13=$VENV/lib/$PYVER/site-packages/nvidia/cu13
if [[ -d $CU13 ]]; then
    ln -sfn lib "$CU13/lib64"
    ln -sf libcudart.so.13 "$CU13/lib/libcudart.so"
    if [[ -n "${CUDA_COMPAT_DIR:-}" ]]; then mkdir -p "$CU13/lib/stubs" && ln -sf "$CUDA_COMPAT_DIR/libcuda.so" "$CU13/lib/stubs/libcuda.so"; fi
fi

# 5. Record exactly what got installed.
source slurm/_common.sh
"$VENV/bin/pip" freeze > requirements.lock
{
    echo "# Environment (generated by slurm/setup_env.sh on $(date -u +%Y-%m-%d))"
    echo; echo '```'
    uname -m; "$VENV/bin/python" --version
    nvidia-smi --query-gpu=name,driver_version --format=csv,noheader | head -1
    "$VENV/bin/python" -c 'import torch, vllm, trl, transformers; print("torch", torch.__version__, "cuda", torch.version.cuda); print("vllm", vllm.__version__); print("trl", trl.__version__); print("transformers", transformers.__version__); print("cuda available", torch.cuda.is_available())'
    echo '```'
} > environment.md
cat environment.md
